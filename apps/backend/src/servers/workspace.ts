import path from 'node:path';
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import type { Server } from '@locternos/shared';
import type { Config } from '../config.js';

/** Root directory of a server's files: `data/servers/<slug>/`. */
export function serverDirectory(config: Config, server: Pick<Server, 'slug'>): string {
  return path.join(config.paths.servers, server.slug);
}

/** Absolute path of the server's `eula.txt`. */
export function eulaPath(serverDir: string): string {
  return path.join(serverDir, 'eula.txt');
}

export interface WorkspaceOptions {
  port: number;
  motd: string;
  maxPlayers?: number;
}

const EULA_ACCEPTED = /^\s*eula\s*=\s*true\s*$/im;

/** True when the given `eula.txt` contents explicitly accept the EULA. */
export function isEulaAcceptedContent(contents: string): boolean {
  return EULA_ACCEPTED.test(contents);
}

/** Reads `eula.txt`; a missing file counts as not accepted. */
export async function isEulaAccepted(serverDir: string): Promise<boolean> {
  try {
    return isEulaAcceptedContent(await readFile(eulaPath(serverDir), 'utf8'));
  } catch {
    return false;
  }
}

/**
 * Writes `eula=true`. Only call this after an explicit user confirmation; the
 * panel must never accept the Minecraft EULA on the user's behalf.
 */
export async function writeEulaAccepted(serverDir: string): Promise<void> {
  await mkdir(serverDir, { recursive: true });
  await writeFile(eulaPath(serverDir), '#Accepted via the Locternos panel\neula=true\n', 'utf8');
}

function defaultServerProperties(options: WorkspaceOptions): string {
  return [
    '#Minecraft server properties',
    '#Generated by Locternos; safe to edit from the panel',
    'enable-command-block=false',
    'level-name=world',
    `max-players=${options.maxPlayers ?? 20}`,
    `motd=${options.motd}`,
    'online-mode=true',
    `server-port=${options.port}`,
    '',
  ].join('\n');
}

/**
 * Creates the server directory and a default `server.properties` when the
 * server has not been booted yet. Existing files are never overwritten, and
 * `eula.txt` is deliberately left untouched.
 */
export async function initializeWorkspace(
  serverDir: string,
  options: WorkspaceOptions,
): Promise<void> {
  await mkdir(serverDir, { recursive: true });

  const propertiesPath = path.join(serverDir, 'server.properties');
  try {
    await access(propertiesPath);
  } catch {
    await writeFile(propertiesPath, defaultServerProperties(options), 'utf8');
  }
}

/** True when the server entrypoint jar exists inside its directory. */
export async function entrypointExists(serverDir: string, entrypointJar: string): Promise<boolean> {
  if (!entrypointJar) return false;
  try {
    await access(path.join(serverDir, path.basename(entrypointJar)));
    return true;
  } catch {
    return false;
  }
}
